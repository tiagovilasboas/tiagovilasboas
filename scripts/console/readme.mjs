// Writes the profile README: every layout row becomes one line of images, each
// image in its own link, so GitHub stacks them into one continuous console.
import { FRAME, esc } from './frame.mjs';

const ASSETS = './assets/console';

function img(t) {
  const width = `${+((t.w / FRAME) * 100).toFixed(2)}%`;
  // align="left" floats the image: no inline baseline gap, so slices touch.
  const tag = `<img src="${ASSETS}/${t.file}" width="${width}" align="left" alt="${esc(t.alt)}">`;
  return t.href ? `<a href="${esc(t.href)}">${tag}</a>` : tag;
}

/** rows: [[tile, ...], ...] where tile = {file, alt, href?, w}. */
export function buildReadme(rows) {
  return `<!-- Generated by scripts/console/render.mjs from scripts/console/content.mjs and live GitHub data. Edit those, not this file. -->
<p align="center">
${rows.map((r) => r.map(img).join('')).join('\n')}
</p>
`;
}
